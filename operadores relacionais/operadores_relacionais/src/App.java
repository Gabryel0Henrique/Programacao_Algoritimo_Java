public class App {
    public static void main(String[] args) throws Exception {
        System.out.println("Operadores Relacionais");

        int num1, num2;
        num1 = 100;
        num2 = 10;



        // Comentario de 1 liha

        /*Comentario
        de muitas
        linhas */

        /*
        > Maior que
        < Menor que
        >= Maior igual
        <= Menor igual
        == Igual
        != Diferente

        A saida sempre retorna Verdadeiro ou Falso
        
        */

        System.out.println(num1 > num2);
        System.out.println(num1 < num2);
        System.out.println(num1 >= num2);
        System.out.println(num1 <= num2);
        System.out.println(num1 == num2);
        System.out.println(num1 != num2);
        
    }
}
